-- Esquema nuevo de pruebas. No aplicar sobre las bases IER heredadas.
CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    enable boolean,
    created_at timestamp(6),
    token_invitacion varchar(255),
    fecha_expiracion_token timestamp(6),
    role_id bigint REFERENCES roles(id)
);

CREATE TABLE investigadores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    area varchar(255),
    especialidad text,
    grado varchar(255),
    bio text,
    biografia text,
    foto_url varchar(255),
    correo_institucional varchar(255),
    updated_at timestamp(6),
    usuario_id bigint UNIQUE REFERENCES users(id)
);

CREATE TABLE laboratorios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    descripcion text,
    imagen_url varchar(255),
    updated_at timestamp(6),
    encargado_id bigint REFERENCES investigadores(id)
);

CREATE TABLE componentes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    descripcion varchar(255),
    tipo varchar(255),
    laboratorio_id bigint NOT NULL REFERENCES laboratorios(id)
);

CREATE TABLE proyectos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo varchar(255) NOT NULL,
    descripcion text,
    estado varchar(255),
    es_destacado boolean,
    imagen_url varchar(255),
    created_by bigint,
    created_at timestamp(6)
);

CREATE TABLE proyecto_investigadores (
    proyecto_id bigint NOT NULL REFERENCES proyectos(id),
    investigador_id bigint NOT NULL REFERENCES investigadores(id),
    PRIMARY KEY (proyecto_id, investigador_id)
);

CREATE TABLE avisos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo varchar(255) NOT NULL,
    contenido text NOT NULL,
    fecha_publicacion timestamp(6),
    imagen_url varchar(255),
    autor_id bigint REFERENCES users(id)
);

CREATE TABLE actividades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo varchar(255) NOT NULL,
    fecha date,
    descripcion varchar(255)
);

CREATE TABLE reservas_laboratorio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha date NOT NULL,
    hora_inicio time(6) NOT NULL,
    hora_fin time(6) NOT NULL,
    laboratorio_id bigint NOT NULL REFERENCES laboratorios(id),
    investigador_id bigint REFERENCES investigadores(id),
    CONSTRAINT reserva_horario_valido CHECK (hora_fin > hora_inicio)
);

CREATE TABLE contacto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    asunto varchar(255),
    mensaje text NOT NULL,
    fecha_envio timestamp(6)
);

CREATE TABLE auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6),
    bio varchar(255),
    destacado boolean,
    updated_by bigint,
    accion varchar(255),
    entidad varchar(255),
    entidad_id bigint
);

